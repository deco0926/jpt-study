def build():
    folder = ROOT / 'site/practice'
    folder.mkdir(parents=True, exist_ok=True)
    manifest = dict(schemaVersion=1, examDate='2026-12-06', timezone='Asia/Taipei', papers=[])
    for n, (title, focus) in enumerate(TITLES):
        day = (date(2026,11,25)+timedelta(days=n)).isoformat()
        rng = random.Random(day)
        questions = []
        for i, entry in enumerate(GENERAL[n]):
            q = row('vocab' if i<2 else 'grammar', '文字・語彙' if i<2 else '文法', entry)
            q['section'] = 'general'; questions.append(q)
        for passage, entries in READING[n]:
            for entry in entries:
                q = row('reading','內容理解・資訊檢索',entry);q.update(section='reading',passage=passage);questions.append(q)
        for script, *entry in LISTENING[n]:
            q=row('listening','課題理解・重點理解・即時應答',entry);q.update(section='listening',script=script);questions.append(q)
        for i,q in enumerate(questions,1):
            q['id']=f'{day}-q{i:02}';rng.shuffle(q['options']);q['answer']=q['options'].index(q.pop('correct'))
            if q['section']=='listening':q['audio']=f'./audio/{day}-q{i:02}.mp3'
        paper=dict(schemaVersion=1,date=day,title=f'N4 濃縮模擬 {n+1:02}｜{title}',focus=focus,
                   answerMinutes=25,reviewMinutes=5,passScore=80,questions=questions)
        (folder/f'{day}.json').write_text(json.dumps(paper,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
        manifest['papers'].append({k:paper[k] for k in ('date','title','focus')})
    (folder/'index.json').write_text(json.dumps(manifest,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
    print('Built 11 daily papers, 220 questions, 66 listening scripts.')

if __name__=='__main__':build()
